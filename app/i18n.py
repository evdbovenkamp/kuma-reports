UNITS = {"en": ("d", "h", "m", "s"), "nl": ("d", "u", "m", "s"), "de": ("T", "Std", "Min", "s")}


class Strings(dict):
    """dict that returns the key itself for missing strings, usable as t.key and t['key'] in templates."""

    def __missing__(self, key):
        return key

    def __getattr__(self, key):
        return self[key]


def strings(lang: str) -> Strings:
    return Strings({**STRINGS["en"], **STRINGS.get(lang, {})})


def fmt_duration(seconds: float | None, lang: str = "en") -> str:
    if seconds is None:
        return "–"
    seconds = int(round(seconds))
    d_, h_, m_, s_ = UNITS.get(lang, UNITS["en"])
    if seconds < 60:
        return f"{seconds}{s_}"
    days, rem = divmod(seconds, 86400)
    hours, rem = divmod(rem, 3600)
    minutes = rem // 60
    parts = []
    if days:
        parts.append(f"{days}{d_}")
    if hours:
        parts.append(f"{hours}{h_}")
    if minutes and not days:
        parts.append(f"{minutes}{m_}")
    return " ".join(parts) or f"0{m_}"


def fmt_pct(value: float | None, decimals: int = 3) -> str:
    if value is None:
        return "–"
    if value >= 100:
        return "100%"
    text = f"{value:.{decimals}f}".rstrip("0").rstrip(".")
    return f"{text}%"


def to_local(dt: datetime | None) -> datetime | None:
    """UTC naive -> local aware."""
    if dt is None:
        return None
    from datetime import timezone
    return dt.replace(tzinfo=timezone.utc).astimezone(config.TIMEZONE)


def fmt_dt(dt: datetime | None, lang: str = "en", with_year: bool = False) -> str:
    """Format a local aware datetime (or UTC naive) for display."""
    if dt is None:
        return "–"
    if dt.tzinfo is None:
        dt = to_local(dt)
    if lang == "en":
        base = dt.strftime("%Y-%m-%d %H:%M") if with_year else dt.strftime("%d %b %H:%M")
    else:
        base = dt.strftime("%d-%m-%Y %H:%M") if with_year else dt.strftime("%d-%m %H:%M")
    return base


def fmt_date_long(dt, lang: str = "en") -> str:
    month = MONTHS.get(lang, MONTHS["en"])[dt.month - 1]
    if lang == "en":
        return f"{month} {dt.day}, {dt.year}"
    return f"{dt.day} {month} {dt.year}" if lang == "nl" else f"{dt.day}. {month} {dt.year}"


def fmt_month(dt, lang: str = "en") -> str:
    return f"{MONTHS.get(lang, MONTHS['en'])[dt.month - 1]} {dt.year}"
